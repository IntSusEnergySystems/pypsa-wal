    rows = []
    top = parks.head(15)
    for _, r in top.iterrows():
        rows.append(f"{tex_escape(r['name'] if isinstance(r['name'], str) else '(unnamed)')} & "
                    f"{num(r['area_ha'], 1)} & "
                    f"{num(r['mw_tag'], 1) if pd.notna(r['mw_tag']) else '--'} & "
                    f"{num(r['mwc_per_ha'], 2) if pd.notna(r['mwc_per_ha']) else '--'} & "
                    f"{tex_escape(labels.get(r['gisement'], r['gisement']))} & "
                    f"{num(100 * r['share_eligible'], 0) if pd.notna(r['share_eligible']) else '--'} \\\\")
    Path(snakemake.output.parks).write_text("\n".join(rows) + "\n")

    rows = []
    for p in snakemake.input.source_meta:
        m = json.loads(Path(p).read_text())
        rows.append(f"{tex_escape(m.get('title') or '')} & \\texttt{{{tex_escape(m['service'])}/{m['layer']}}} & "
                    f"{num(m['features_written'])} & {m['retrieved'][:10]} \\\\")
    Path(snakemake.output.sources).write_text("\n".join(rows) + "\n")
