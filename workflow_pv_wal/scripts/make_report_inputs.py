"""
LaTeX macros and table fragments for docs/pv_potential_wallonia/.

Every number the report quotes is a macro written here from the workflow's
outputs, so the text cannot drift from the calculation.  Macro names are
CamelCase versions of the workflow keys: ``\\GSarRefMW`` is the reference
capacity of the ``sar`` gisement, ``\\SAgriQuotaPct`` the change a case makes,
``\\LNaturaKm`` the area of a burnt layer.
"""

import json
import re
from pathlib import Path

import pandas as pd

GROUP_LABEL = {"policy": "policy", "judgement": "judgement", "technical": "technical"}


def camel(key):
    key = key.replace("06", "ZeroSix")
    parts = re.split(r"[_\-\s]+", key)
    out = "".join(p[:1].upper() + p[1:] for p in parts if p)
    # LaTeX command names take letters only
    digits = {"0": "Zero", "1": "One", "2": "Two", "3": "Three", "4": "Four", "5": "Five",
              "6": "Six", "7": "Seven", "8": "Eight", "9": "Nine"}
    return "".join(digits.get(c, c) for c in out)


def num(x, d=0):
    """1234567.8 -> 1\\,234\\,568 (thin-space thousands, decimal point)."""
    if x is None or (isinstance(x, float) and pd.isna(x)):
        return "--"
    s = f"{x:,.{d}f}"
    return s.replace(",", "\\,")


def gw(mw, d=1):
    return num(mw / 1000.0, d)


class Macros:
    def __init__(self):
        self.lines = []
        self.names = set()

    def add(self, name, value):
        if name in self.names:
            raise ValueError(f"duplicate macro {name}")
        self.names.add(name)
        self.lines.append(f"\\newcommand{{\\{name}}}{{{value}}}")

    def text(self):
        return "% Generated by workflow_pv_wal/scripts/make_report_inputs.py -- do not edit.\n" + \
            "\n".join(self.lines) + "\n"


def tex_escape(s):
    return (str(s).replace("\\", "\\textbackslash{}").replace("&", "\\&").replace("%", "\\%")
            .replace("_", "\\_").replace("#", "\\#").replace("$", "\\$")
            .replace("§", "\\S{}").replace("°", "\\textdegree{}").replace("—", "---")
            .replace("–", "--").replace("²", "\\textsuperscript{2}").replace("…", "\\ldots{}"))


