        M.add(f"FleetAvoid{c}", num(r["avoidance"], 2) if pd.notna(r["avoidance"]) else "--")
        M.add(f"FleetShare{c}", num(100 * r["share_fleet"], 0))
        M.add(f"RegionShare{c}", num(100 * r["share_region"], 0))
