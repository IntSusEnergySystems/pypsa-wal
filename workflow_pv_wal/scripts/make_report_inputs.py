    for p in snakemake.input.layer_stats:
        s = json.loads(Path(p).read_text())
        M.add(f"L{camel(s['layer'])}Km", num(s["area_km2"]))

    # ---- benchmarks -------------------------------------------------------------------------------
    M.add("ModelCapMW", num(B["model_p_nom_max_mw"]))
    M.add("ModelCapGW", gw(B["model_p_nom_max_mw"], 0))
    M.add("ModelRoofGW", gw(B["model_rooftop_p_nom_max_mw"], 0))
    M.add("PypsaEurGW", gw(B["pypsa_eur_land_mw"], 0))
    M.add("InstalledGW", gw(B["installed_total_2025_mwc"]))
    M.add("PaceGWh", num(B["pace_2030_gwh"]))
    M.add("PaceGW", num(B["pace_2030_gwc"], 0))
    M.add("ApereGW", num(B["apere_brownfields_gwc"], 1))
    M.add("LbRemainingMW", num(B["livre_blanc_remaining_mwc"]))
    M.add("LbRemainingHa", num(B["livre_blanc_remaining_ha"]))
