    ev = json.loads(Path(snakemake.input.evidence).read_text())
    M.add("EvShare", num(100 * ev["share"], 1))
    for k, v in ev["steps_ha"].items():
        M.add(f"Ev{camel(k.replace('_ha', ''))}Ha", num(v))
    fs = ev["farmed_share_by_awac_class"]
    for c in range(1, 6):
        M.add(f"EvFarmedClass{['One', 'Two', 'Three', 'Four', 'Five'][c - 1]}", num(100 * fs.get(str(c), fs.get(c, 0)), 0))
    M.add("EvUnfarmedPoor", num(100 * ev["unfarmed_share_poor"], 1))
    M.add("EvUnfarmedOther", num(100 * ev["unfarmed_share_other"], 1))
    M.add("EvPoorRegionHa", num(ev["poor_soils_region_ha"]))
    M.add("EvPoorFarmedHa", num(ev["poor_soils_farmed_ha"]))
    M.add("EvPoorFarmedPct", num(100 * ev["poor_soils_farmed_ha"] / ev["poor_soils_region_ha"], 0))
    stony = sum(v for k, v in ev["poor_soils_by_cnsw_ha"].items() if str(k).startswith("7"))
    M.add("EvPoorStonyPct", num(100 * stony / ev["poor_soils_region_ha"], 0))
    M.add("EvCurtilage", num(ev["curtilage_m"]))

