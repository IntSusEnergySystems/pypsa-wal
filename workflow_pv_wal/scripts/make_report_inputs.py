    head = json.loads(Path(snakemake.input.headline).read_text())
    detail = json.loads(Path(snakemake.input.detail).read_text())
    sens = pd.read_csv(snakemake.input.sensitivity)
    fleet = json.loads(Path(snakemake.input.fleet).read_text())
    avoid = pd.read_csv(snakemake.input.avoidance)
    parks = pd.read_csv(snakemake.input.parks)
    energy = json.loads(Path(snakemake.input.energy).read_text())
    grid = json.loads(Path(snakemake.input.grid).read_text())
    M = Macros()
    B = cfg["benchmarks"]

    # ---- region, funnel -------------------------------------------------------------
    region_ha = head["region_ha"]
    M.add("RegionKm", num(region_ha / 100))
    M.add("GridRes", num(grid["res"]))
    prev = region_ha
    for f in head["funnel"]:
        k = camel(f["family"])
        M.add(f"Left{k}Km", num(f["left_ha"] / 100))
        M.add(f"Left{k}Pct", num(100 * f["left_ha"] / region_ha, 1))
        M.add(f"Drop{k}Km", num((prev - f["left_ha"]) / 100))
        prev = f["left_ha"]
    park = next(f for f in head["funnel"] if f["family"] == "park_rule")
    M.add("FloatHa", num(park["floating_ha"]))

    # ---- gisements ---------------------------------------------------------------------
    g = head["gisements"]
    agri = [k for k, v in g.items() if v["system"].startswith("agrivoltaic")]
    for k, v in g.items():
        c = camel(k)
        M.add(f"G{c}EligHa", num(v["eligible_ha"]))
        M.add(f"G{c}TechHa", num(v["after_park_rule_ha"]))
        M.add(f"G{c}OpenHa", num(v["open_ha"]))
        M.add(f"G{c}TechMW", num(v["technical_mwc"]))
        M.add(f"G{c}TechGW", gw(v["technical_mwc"]))
        M.add(f"G{c}RefMW", num(v["policy_mwc"]))
    ref = head["reference"]
    M.add("RefMW", num(ref["policy_mwc"]))
    M.add("RefGW", gw(ref["policy_mwc"]))
    M.add("RefHa", num(ref["open_ha"]))
    M.add("TechMW", num(ref["technical_mwc"]))
    M.add("TechGW", gw(ref["technical_mwc"], 0))
    tech_nonagri = sum(v["technical_mwc"] for k, v in g.items() if k not in agri)
    tech_agri = sum(v["technical_mwc"] for k in agri for v in [g[k]])
    M.add("TechNonAgriGW", gw(tech_nonagri))
    M.add("TechAgriGW", gw(tech_agri, 0))
    agri_ha = sum(g[k]["after_park_rule_ha"] for k in agri)
    M.add("TechAgriHa", num(agri_ha))
    M.add("TechAgriShareSau", num(100 * agri_ha / B["sau_ha"], 0))
    deg = ["sar", "cet", "terril", "extraction", "infra_edge", "water_industrial"]
    M.add("RefCapHa", num(ref["agri_cap_ha"] or 0))
    M.add("RefDegradedGW", gw(sum(g[k]["policy_mwc"] for k in deg)))
    M.add("RefZaeGW", gw(g["zae"]["policy_mwc"] + g["zspec"]["policy_mwc"]))
    M.add("RefZaeShare", num(100 * ref["shares"]["zae"]))
    # the park rule re-applied: what filtering once would have given
    M.add("ParkMinHa", num(cfg["park"]["min_area_ha"], 0))
    M.add("ParkMinWidth", num(cfg["park"]["min_width_m"]))

    # ---- densities, policy ------------------------------------------------------------
    for k, v in cfg["densities_mwc_ha"].items():
        c = camel(k)
        M.add(f"Dens{c}", num(v["ref"], 2))
        M.add(f"Dens{c}Low", num(v["low"], 2))
        M.add(f"Dens{c}High", num(v["high"], 2))
    M.add("FloatCover", num(100 * cfg["floating"]["coverage"]["ref"]))
    M.add("SlopeMax", num(cfg["terrain"]["max_slope_pct"]))
    M.add("NorthMax", num(cfg["terrain"]["north_max_slope_pct"]))
    M.add("BuiltPct", num(cfg["walous"]["thresholds_pct"]["built"]))
    M.add("SealedPct", num(cfg["walous"]["thresholds_pct"]["sealed"]))
    M.add("TreesPct", num(cfg["walous"]["thresholds_pct"]["trees"]))
    M.add("SauHa", num(B["sau_ha"]))
    M.add("SauKha", num(B["sau_ha"] / 1000))

