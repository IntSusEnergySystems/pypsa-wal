    M.add("FleetHa", num(fleet["area_ha"]))
    M.add("FleetEligPct", num(100 * fleet["share_of_fleet_area_eligible"]))
    M.add("FleetEligRulesPct", num(100 * fleet["share_of_fleet_area_eligible_without_landcover_built"]))
